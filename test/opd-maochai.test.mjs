import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

/* สัญญาเพิ่มเติม โอพีดี เหมาจ่าย

   เอกสารอ้างอิง เงื่อนไขทั่วไปของสัญญาเพิ่มเติม โอพีดี เหมาจ่าย ฉบับเต็ม
   และเอกสารสรุปแบบประกันภัยภายใน เริ่มขาย 3 พฤษภาคม 2566

   เดิมหน้าเว็บเอาแบบนี้ไปรวมหน้าเดียวกับ OPD รายครั้ง ซึ่งทำให้เข้าใจผิดหนัก
   เพราะสองแบบนี้ต่างกันแทบทุกข้อ ทั้งรูปแบบวงเงิน จำนวนครั้ง ค่ายา และอายุรับ
   จึงแยกเป็นคนละหน้า และเทสต์ชุดนี้กันไม่ให้ข้อมูลของสองแบบปนกันอีก */

const root = new URL('../', import.meta.url);
const html = readFileSync(new URL('index.html', root), 'utf8');
const RATES = JSON.parse(readFileSync(new URL('data/premium-rates.json', root), 'utf8'));

const block = (key, next) => {
  const i = html.indexOf(`  ${key}: {`);
  assert.notEqual(i, -1, `ไม่พบบล็อกของแผน ${key}`);
  const j = html.indexOf(`  ${next}: {`, i);
  assert.notEqual(j, -1, `ไม่พบจุดจบของบล็อก ${key}`);
  return html.slice(i, j);
};
const maochai = block('opdmaochai', 'careplus');
const krang = block('opd', 'opdmaochai');

test('ต้องเป็นหน้าของตัวเอง มี route และการ์ดบนหน้าแผน', () => {
  assert.ok(html.includes("opdmaochai: '/plans/opd-maochai'"), 'ยังไม่มี route ของหน้าเหมาจ่าย');
  assert.ok(html.includes("showPlanDetail('opdmaochai')"), 'ไม่มีปุ่มเข้าหน้าเหมาจ่าย');
  // การ์ดสองใบต้องแยกกันจริง ไม่ใช่ใบเดียวที่พูดถึงทั้งสองแบบ
  assert.ok(html.includes('<h3>สัญญาเพิ่มเติม การรักษาพยาบาลผู้ป่วยนอก (OPD รายครั้ง)</h3>'), 'ไม่มีการ์ดแบบรายครั้ง');
  assert.ok(html.includes('<h3>สัญญาเพิ่มเติม โอพีดี เหมาจ่าย</h3>'), 'ไม่มีการ์ดแบบเหมาจ่าย');
  assert.ok(!html.includes('<h3>OPD รายครั้ง / OPD เหมาจ่าย</h3>'), 'ยังเหลือการ์ดเก่าที่รวมสองแบบไว้ใบเดียว');
});

test('อายุรับของเหมาจ่ายต้องเป็น 6 ถึง 90 ไม่ใช่ 6 ถึง 80', () => {
  /* ของเดิมหน้าเว็บเขียนว่ารับ 6-80 ต่ออายุถึง 90 ซึ่งผิดทั้งคู่
     ของจริงคือรับ 6-90 ต่ออายุถึง 98 คุ้มครองถึง 99 */
  assert.ok(maochai.includes('อายุที่รับประกันภัย 6 – 90 ปี'), 'อายุรับของเหมาจ่ายไม่ถูก');
  assert.ok(maochai.includes('ต่ออายุได้จนถึงอายุ 98 ปี'), 'อายุต่ออายุไม่ถูก');
  assert.ok(maochai.includes('ถึงอายุ 99 ปี'), 'อายุคุ้มครองไม่ถูก');
  assert.ok(!html.includes('OPD เหมาจ่ายต่ออายุได้ถึง 90 ปี'), 'ยังเหลือข้อความอายุเก่าที่ผิด');
});

