test('ตารางอัตราต้องครบ 7 แบบ ทุกงวดชำระ อายุ 6 ถึง 98', () => {
  assert.equal(OPD.age_start, 6);
  for(const freq of ['annual','semiannual','quarterly','monthly']){
    const t = OPD.payment_schedules[freq];
    assert.ok(t, `ไม่มีตารางงวด ${freq}`);
    for(const p of PLANS) for(const g of ['m','f']){
      const arr = t[g + '_' + p];
      assert.ok(Array.isArray(arr), `งวด ${freq} แบบ ${p} เพศ ${g} ไม่มีตาราง`);
      assert.equal(arr.length, 93, `งวด ${freq} แบบ ${p} เพศ ${g} ช่วงอายุไม่ครบ 6-98`);
      assert.ok(arr.every(v => typeof v === 'number' && v > 0), `งวด ${freq} แบบ ${p} เพศ ${g} มีช่องว่าง`);
    }
  }
});

test('อัตราเบี้ยรายปีต้องตรงกับเอกสารทางการ 15.02.64 ทุกช่อง', () => {
  const t = OPD.payment_schedules.annual;
  let checked = 0;
  for(const p of PLANS){
    BANDS.forEach(([lo, hi], bi) => {
      const [wm, wf] = ANNUAL[p][bi];
      for(let age = lo; age <= hi; age++){
        assert.equal(t['m_' + p][age - 6], wm, `แบบ ${p} ชายอายุ ${age}`);
        assert.equal(t['f_' + p][age - 6], wf, `แบบ ${p} หญิงอายุ ${age}`);
        checked += 2;
      }
    });
  }
  assert.equal(checked, 1302, 'จำนวนช่องที่ตรวจเปลี่ยนไป แปลว่าช่วงอายุหรือจำนวนแบบเปลี่ยน');
});

test('อัตราไม่ควรมีค่าที่ต่ำกว่าแบบที่วงเงินน้อยกว่า', () => {
  // วงเงินสูงกว่าต้องเบี้ยแพงกว่าเสมอที่อายุเดียวกัน ถ้าสวนทางแปลว่าคอลัมน์เลื่อน
  const t = OPD.payment_schedules.annual;
  for(let i = 1; i < PLANS.length; i++){
    for(const g of ['m','f']){
      const lo = t[g + '_' + PLANS[i-1]], hi = t[g + '_' + PLANS[i]];
      for(let k = 0; k < lo.length; k++){
        assert.ok(hi[k] >= lo[k],
          `แบบ ${PLANS[i]} ถูกกว่าแบบ ${PLANS[i-1]} ที่อายุ ${k + 6} เพศ ${g}`);
      }
    }
  }
});

