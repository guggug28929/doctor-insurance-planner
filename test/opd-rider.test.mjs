test('ชุดระยะรอคอยกลางต้องมีครบ 5 ชั้น และชั้น 180 วันต้องมีรายชื่อโรค', () => {
  const i = html.indexOf('const WAITING_PERIOD_TIERS = [');
  assert.notEqual(i, -1, 'ไม่พบชุดระยะรอคอยกลาง');
  const block = html.slice(i, html.indexOf('\n];', i));
  for(const w of ['คุ้มครองทันที', '30 วัน', '120 วัน', '180 วัน', '280 วัน']){
    assert.ok(block.includes(`wait:'${w}'`), `ขาดชั้น ${w}`);
  }
  const chronic = block.slice(block.indexOf("wait:'180 วัน'"));
  for(const d of ['เบาหวาน','ความดันโลหิตสูง','โรคหัวใจ','ภูมิแพ้','ไทรอยด์','โรคกระเพาะอาหาร','ลมบ้าหมู']){
    assert.ok(chronic.includes(d), `ชั้น 180 วันขาดโรค ${d}`);
  }
  assert.ok(block.includes('เฉพาะความคุ้มครองผู้ป่วยนอก'),
    'ต้องระบุว่าชั้น 180 วันมีเฉพาะฝั่งผู้ป่วยนอก ไม่ใช่ทุกความคุ้มครอง');
});

